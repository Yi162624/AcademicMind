# skills/paper_deep_read/prompts.py
# 作用：存放单篇论文精读 skill 的全部 LLM 提示词模板（纯字符串常量，不参与运行逻辑）
# 位置：skills/paper_deep_read/，被 skill.py import 后填进 chat() 调用
#
# v3 五阶段提示词：
#   Stage0 结构地图（论文怎么组织）→ Stage1 推理知识库（作者为什么这么做）→

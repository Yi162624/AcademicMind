# ============================================================

JSON_RULES = """
【JSON 输出规范，务必逐条遵守】
1. 只输出 JSON 本身，不要用 ``` 代码块包裹，不要在 JSON 前后加任何解释文字。
2. JSON 字符串值里的英文双引号必须转义（写成反斜杠加双引号），不能出现未转义的英文双引号。
3. 数组或对象的最后一个元素后面不要加逗号（不允许尾逗号）。
4. 输出前自查：确保整段内容能被 Python 的 json.loads() 直接解析，否则算失败。
"""



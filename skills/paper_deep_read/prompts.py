STAGE1_REASONING_PROMPT = """
你是论文推理分析专家。

你的任务不是写摘要，也不是罗列"论文有什么内容"，而是还原作者的"推理链"：
如果作者坐在你面前，他会如何一步步解释"为什么提出这个方法、为什么这样设计、实验如何证明它"。

论文不是知识集合，而是一条推理链：
现实问题 → 已有方案 → 已有方案为什么失败 → 关键观察 → 新假设 → 方法设计 → 实验验证。

请基于论文全文、图表说明、结构地图，输出严格 JSON（字段含义见下方说明，务必写充分，不要偷懒只写一句）：

{
  "paper_identity": {"title": "", "authors": [], "year": "", "field": "", "venue": ""},
  "research_story": {
    "background": "",
    "old_methods": [],
    "old_method_limitations": [],
    "research_gap": "",
    "author_question": "",
    "key_observation": "",
    "new_hypothesis": ""
  },
  "design_reasoning": [
    {"problem": "", "choice": "", "why": "", "alternative": "", "evidence": ""}
  ],
  "concept_knowledge": [
    {"name": "", "intuition": "", "problem_solved": "", "example": "", "technical_definition": ""}
  ],
  "evidence_chain": [
    {"claim": "", "evidence": "", "location": "", "figure_table": ""}
  ],
  "experiment_reasoning": [
    {"question": "", "experiment": "", "result": "", "meaning": "", "practical_significance": ""}
  ],
  "author_limitations": [],
  "unmentioned_limitations": [],
  "impact": "",
  "future_work": "",
  "reading_guide": ""
}

字段说明（重点理解"为什么"，而不是"是什么"）：
- paper_identity.authors：作者姓名数组（如 ["张三","李四"]）
- paper_identity.field：论文所属研究领域
- paper_identity.venue：发表会议/期刊名（如 "NeurIPS 2017"），没有就留空
- research_story.background：这个问题为什么重要（前因后果，2-4 句）
- research_story.old_methods：论文出现前，大家怎么解决这个问题
- research_story.old_method_limitations：旧方法的具体缺陷/失败原因
- research_story.research_gap：旧方法留下的研究空白
- research_story.author_question：作者要回答的核心问题
- research_story.key_observation：作者发现了什么关键观察（推理链的转折点，最重要）
- research_story.new_hypothesis：作者基于观察提出的新假设
- design_reasoning：方法设计里每个"为什么这样设计"的决策。problem=要解决的具体问题，choice=作者的选择，why=为什么这样选，alternative=还有什么替代方案，evidence=支撑这个选择的证据
- concept_knowledge：需要向读者解释的核心概念（不是参数符号）。name=概念名，intuition=大白话直觉，problem_solved=它解决什么问题，example=举例，technical_definition=技术定义
- evidence_chain：论文里每个关键结论绑定证据。claim=结论，evidence=证据内容，location=章节位置，figure_table=对应的图表
- experiment_reasoning：每个实验的推理。question=这个实验想验证什么，experiment=做了什么，result=结果如何，meaning=结果证明了什么，practical_significance=结果在实际应用中到底有没有用（区分"统计上显著"和"实际上有意义"，两者不等同）
- author_limitations：论文作者自己承认的局限（通常写在 Discussion/Limitations 里），只挑最关键的 2-3 条，不要列太多
- unmentioned_limitations：作者没有明说、但客观存在的重要局限，同样只挑最关键的 2-3 条
- impact：论文声称的贡献（它改变了什么）
- future_work：论文提出的未来工作
- reading_guide：建议读者怎么读这篇论文

硬性要求：
1. 只使用论文明确提供的信息，不编造。
2. 重点写清"推理链"，尤其是 key_observation（关键观察）和 design_reasoning（为什么这样设计）。
3. 每个字段按说明写充分，不要只写一句话；但数组类字段（design_reasoning/concept_knowledge/evidence_chain/experiment_reasoning）各收 3-5 项即可，
   只留对理解论文真正重要的，不要为凑数量硬塞——控制整体篇幅，避免输出过长导致 JSON 不完整。
4. 根据论文类型（结构地图里的 paper_type）调整分析重点：
   - AI/CS：重点剖析架构设计、ablation 实验、计算成本、可复现性
   - 实验研究(RCT等)：重点看实验设计、统计检验、内外部效度
   - 质性研究：重点看理论建构、样本代表性、理论饱和
   - 系统综述：重点看纳入排除标准、异质性、出版偏倚

论文全文：
{paper_text}

图表说明：
{figure_notes}

结构地图：
{structure_map}
""" + JSON_RULES


